import esbuild from 'esbuild'
import process from 'process'
import { builtinModules } from 'node:module'
import { buildCss } from './scripts/buildCss.mjs'
import { reactDomScriptsPlugin } from './scripts/reactDomScripts.mjs'

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`

const prod = process.argv[2] === 'production'

// Tailwind reads class names from the TypeScript sources, so the stylesheet is
// rebuilt after every JavaScript build.
const stylesPlugin = {
  name: 'tasks-table-styles',
  setup(build) {
    build.onEnd(async (result) => {
      if (result.errors.length > 0) {
        return
      }
      try {
        await buildCss({ minify: prod })
      } catch (error) {
        console.error('styles.css build failed:', error)
        if (prod) {
          process.exitCode = 1
        }
      }
    })
  },
}

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  loader: { '.wasm': 'binary' },
  define: { 'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development') },
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: prod,
  plugins: [reactDomScriptsPlugin, stylesPlugin],
})

if (prod) {
  await context.rebuild()
  await context.dispose()
} else {
  await context.watch()
}
